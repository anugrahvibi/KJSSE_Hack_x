import React, { useState, useEffect } from 'react';
import { 
  FileText, 
  Shield, 
  CheckCircle2, 
  XCircle, 
  ArrowLeft, 
  Download, 
  Share2, 
  AlertTriangle,
  History,
  Activity,
  Award
} from 'lucide-react';
import { useGsapAnimations } from '../utils/useGsapAnimations';
import { useRef } from 'react';

export function AccountabilityReport({ onClose }: { onClose?: () => void }) {
  const containerRef = useRef<HTMLDivElement>(null);
  const [loading, setLoading] = useState(true);
  const [report, setReport] = useState<any>(null);

  useGsapAnimations(containerRef);

  useEffect(() => {
    async function getReport() {
      try {
        // Force a 2-second delay to show the "Groq is generating" state
        await new Promise(resolve => setTimeout(resolve, 2000));
        
        const response = await fetch('http://localhost:8000/api/accountability/generate?ward_id=ward_h_east');
        const data = await response.json();
        setReport(data);
      } catch (error) {
        console.error("Failed to fetch report:", error);
      } finally {
        setLoading(false);
      }
    }
    getReport();
  }, []);

  if (loading) {
    return (
      <div className="fixed inset-0 z-[100] bg-white/90 backdrop-blur-2xl flex flex-col items-center justify-center space-y-8 animate-in fade-in duration-1000">
        <div className="relative">
           <div className="w-32 h-32 border-4 border-blue-600/10 rounded-full animate-pulse" />
           <div className="absolute inset-0 w-32 h-32 border-t-4 border-blue-600 rounded-full animate-spin" />
           <Activity className="absolute inset-0 m-auto text-blue-600 animate-pulse" size={40} />
        </div>
        <div className="text-center space-y-2">
           <h2 className="text-2xl font-black text-gray-900 brand-font uppercase">Fusing Accountability Log</h2>
           <p className="text-gray-400 font-bold uppercase text-[12px] tracking-[0.2em] animate-pulse">Groq is generating report...</p>
        </div>
      </div>
    );
  }

  return (
    <div ref={containerRef} className="fixed inset-0 z-[100] bg-slate-50/95 backdrop-blur-3xl overflow-y-auto custom-scrollbar p-6 sm:p-12">
      <div className="max-w-4xl mx-auto space-y-12 pb-20">
        <header className="flex justify-between items-start">
           <button onClick={onClose} className="w-12 h-12 bg-white rounded-2xl flex items-center justify-center border border-black/5 shadow-sm hover:scale-95 transition-all">
              <ArrowLeft size={24} />
           </button>
           <div className="flex gap-4">
              <button className="flex items-center gap-2 px-6 py-3 bg-white rounded-2xl border border-black/5 font-black text-[12px] uppercase shadow-sm">
                 <Download size={14} /> PDF
              </button>
              <button className="flex items-center gap-2 px-6 py-3 bg-slate-900 text-white rounded-2xl font-black text-[12px] uppercase shadow-lg shadow-black/20">
                 <Share2 size={14} /> Dispatch to NDMA
              </button>
           </div>
        </header>

        <section className="space-y-6">
           <div className="flex items-center gap-4">
              <div className="w-16 h-16 bg-blue-600 rounded-[1.5rem] flex items-center justify-center shadow-xl shadow-blue-500/30">
                 <FileText className="text-white" size={32} />
              </div>
              <div>
                 <h1 className="text-4xl font-black text-gray-900 brand-font uppercase">{report?.report_title || "Accountability Post-Action Report"}</h1>
                 <p className="text-[12px] font-black text-gray-400 uppercase tracking-widest mt-1">Generated by RIVA GenAI · Event ID: MUM-2024-07-15A</p>
              </div>
           </div>
           
           <div className="glass-card p-10 rounded-[3rem] border border-white/40 shadow-xl bg-white/50 space-y-4">
              <h3 className="text-[14px] font-black text-blue-600 uppercase flex items-center gap-2">
                 <History size={16} /> Event Summary
              </h3>
              <p className="text-xl font-bold leading-relaxed text-gray-900 italic">
                 "{report?.event_summary || "The compound flood event on July 15th was characterized by a 4.6m high tide synchronized with 87mm/hr rainfall. Despite RIVA detecting the impending 'Deadlock' at T-0, institutional latency in the Western Railway department cost 48 minutes of response time, leading to service submersion at Kurla."}"
              </p>
           </div>
        </section>

        <section className="space-y-6">
           <h3 className="text-[14px] font-black text-gray-900 uppercase flex items-center gap-3">
              <Award size={18} className="text-emerald-600" /> Department Performance Audit
           </h3>
           <div className="overflow-hidden glass-card rounded-[2.5rem] border border-white/40 shadow-xl bg-white">
              <table className="w-full text-left border-collapse">
                 <thead className="bg-slate-50 border-b border-black/5">
                    <tr>
                       <th className="p-6 text-[12px] font-black uppercase text-gray-500">Agency</th>
                       <th className="p-6 text-[12px] font-black uppercase text-gray-500">Status</th>
                       <th className="p-6 text-[12px] font-black uppercase text-gray-500">AI Assessment</th>
                    </tr>
                 </thead>
                 <tbody className="divide-y divide-black/5">
                    {(report?.department_performance || [
                       { dept: "BMC Ward Officer", status: "ACKNOWLEDGED", assessment: "High-agility response; pump mobilization within threshold." },
                       { dept: "NDRF Battalion", status: "ACKNOWLEDGED", assessment: "Deployment successful; pre-positioned before Sion closure." },
                       { dept: "Western Railway", status: "FAILED", assessment: "Critical delay (OVERDUE); Matunga sector submerged before halt." },
                       { dept: "KEM Hospital", status: "ACKNOWLEDGED", assessment: "Surge protocol active; ambulance rerouting optimal." }
                    ]).map((row: any, i: number) => (
                       <tr key={i} className="hover:bg-slate-50/50 transition-colors">
                          <td className="p-6 font-black text-gray-950 uppercase text-[14px]">{row.dept}</td>
                          <td className="p-6">
                             <span className={`px-4 py-1.5 rounded-full text-[10px] font-black uppercase ${
                                row.status === 'FAILED' ? 'bg-red-100 text-red-600' : 'bg-emerald-100 text-emerald-600'
                             }`}>
                                {row.status}
                             </span>
                          </td>
                          <td className="p-6 text-[13px] font-medium text-gray-700 leading-snug">{row.assessment}</td>
                       </tr>
                    ))}
                 </tbody>
              </table>
           </div>
        </section>

        <section className="grid grid-cols-1 md:grid-cols-2 gap-8">
           <div className="glass-card p-10 rounded-[3rem] border border-red-200 shadow-xl bg-red-50/30 space-y-6">
              <h3 className="text-[14px] font-black text-red-600 uppercase flex items-center gap-2">
                 <AlertTriangle size={18} /> Institutional Assessment
              </h3>
              <p className="text-[15px] font-bold text-gray-900 leading-relaxed">
                 {report?.institutional_assessment || "The failure of Western Railway to acknowledge the T-15 alert within the mandated 10-minute window directly resulted in the water-logging of the slow-track corridor. AI assessment suggests a breakdown in the signal-to-command chain at Kurla junction."}
              </p>
           </div>
           
           <div className="glass-card p-10 rounded-[3rem] border border-blue-200 shadow-xl bg-blue-50/30 space-y-6">
              <h3 className="text-[14px] font-black text-blue-600 uppercase flex items-center gap-2">
                 <Shield size={18} /> Recommended Policy
              </h3>
              <ul className="space-y-4">
                 {(report?.recommended_actions || [
                   "Mandate Haptic Override for Railway Command during Red Vectors.",
                   "Upgrade Kurla culverts to 1200mm to allow gravity bypass.",
                   "Enforce multi-agency drills for Sion-Matrix synchronization."
                 ]).map((rec: string, i: number) => (
                    <li key={i} className="flex gap-3 text-[14px] font-bold text-gray-700 leading-tight italic">
                       <CheckCircle2 size={16} className="text-blue-600 shrink-0" /> "{rec}"
                    </li>
                 ))}
              </ul>
           </div>
        </section>
      </div>
    </div>
  );
}
